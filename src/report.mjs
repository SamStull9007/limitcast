// @ts-check
import { homedir } from 'node:os';
import { total } from './usage.mjs';

/** @typedef {import('./usage.mjs').Usage} Usage */

/**
 * Weekly burn report as Markdown: totals, per day, per project, per model, top sessions, subagent share.
 * @param {Usage[]} usage
 * @param {{since:number, now:number}} range
 */
export function burnReport(usage, { since, now }) {
  const sum = (/** @type {Usage[]} */ xs) => xs.reduce((a, u) => a + total(u), 0);
  const all = sum(usage);
  const lines = [`# limitcast burn report`, '', `${day(since)} to ${day(now)} · ${fmt(all)} tokens`, ''];
  if (!usage.length) return [...lines, 'No Claude Code or Codex usage in this period.'].join('\n');

  const byTool = group(usage, (u) => u.src);
  lines.push('| tool | tokens | output | cache reads | share |', '|---|---:|---:|---:|---:|');
  for (const [k, xs] of byTool) {
    lines.push(
      `| ${k} | ${fmt(sum(xs))} | ${fmt(xs.reduce((a, u) => a + u.output, 0))} | ${fmt(xs.reduce((a, u) => a + u.cacheRead, 0))} | ${pct(sum(xs), all)} |`,
    );
  }

  const claude = usage.filter((u) => u.src === 'claude');
  if (claude.length) {
    const side = sum(claude.filter((u) => u.sidechain));
    lines.push('', `Subagents used **${pct(side, sum(claude))}** of Claude tokens.`);
  }

  table(
    lines,
    'By day',
    group(usage, (u) => day(u.t)),
    sum,
    all,
    false,
  );
  // Ranked by new tokens (input, cache writes, output): cached reads barely count against the limit.
  const fresh = (/** @type {Usage[]} */ xs) => xs.reduce((a, u) => a + u.input + u.cacheWrite + u.output, 0);
  const allFresh = fresh(usage);
  table(
    lines,
    'Top projects',
    group(usage, (u) => short(u.project) || '(unknown)'),
    fresh,
    allFresh,
    true,
    8,
    'new tokens',
  );
  table(
    lines,
    'By model',
    group(usage, (u) => u.model || '(unknown)'),
    fresh,
    allFresh,
    true,
    6,
    'new tokens',
  );
  table(
    lines,
    'Heaviest sessions',
    group(usage, (u) => `${u.src} ${u.session.slice(0, 8)} · ${short(u.project)}`),
    fresh,
    allFresh,
    true,
    5,
    'new tokens',
  );
  lines.push('', `_Generated by limitcast. Token counts come from your local Claude Code and Codex logs._`);
  return lines.join('\n');
}

/**
 * @param {string[]} lines
 * @param {string} title
 * @param {Map<string, Usage[]>} groups
 * @param {(xs:Usage[])=>number} sum
 * @param {number} all
 * @param {boolean} sortBySize
 * @param {number} [limit]
 * @param {string} [col] header of the token column
 */
function table(lines, title, groups, sum, all, sortBySize, limit = Infinity, col = 'tokens') {
  let rows = [...groups].map(([k, xs]) => /** @type {[string, number]} */ ([k, sum(xs)]));
  rows = sortBySize ? rows.sort((a, b) => b[1] - a[1]) : rows.sort((a, b) => a[0].localeCompare(b[0]));
  lines.push('', `## ${title}`, '', `| | ${col} | share |`, '|---|---:|---:|');
  for (const [k, n] of rows.slice(0, limit)) lines.push(`| ${k} | ${fmt(n)} | ${pct(n, all)} |`);
}

/**
 * @template T
 * @param {T[]} xs
 * @param {(x:T)=>string} key
 */
function group(xs, key) {
  /** @type {Map<string, T[]>} */
  const m = new Map();
  for (const x of xs) {
    const k = key(x);
    if (!m.has(k)) m.set(k, []);
    m.get(k)?.push(x);
  }
  return m;
}

/** @param {number} n */
export const fmt = (n) =>
  n >= 1e9 ? `${(n / 1e9).toFixed(2)}B` : n >= 1e6 ? `${(n / 1e6).toFixed(1)}M` : n >= 1e3 ? `${(n / 1e3).toFixed(1)}k` : `${n}`;
/** @param {number} n @param {number} d */
const pct = (n, d) => (d ? `${Math.round((n / d) * 100)}%` : '-');
/** @param {number} t */
const day = (t) => new Date(t).toLocaleDateString('sv-SE'); // local YYYY-MM-DD
/** @param {string} p */
const short = (p) => p.replace(homedir(), '~');
