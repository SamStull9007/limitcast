// `limitcast results --html`: the Markdown reports as one self-contained page (no scripts, no network).

/** @param {string} s */
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/** Inline Markdown: **bold**, `code`, _italic_. @param {string} s */
const inline = (s) =>
  esc(s)
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/(^|\s)_(.+?)_(?=\s|$|[.,;:])/g, '$1<em>$2</em>');

/**
 * The subset of Markdown limitcast's reports use: headings, bullet lists, tables, paragraphs.
 * @param {string} md
 */
export function mdToHtml(md) {
  const out = [];
  const lines = md.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const h = /^(#{1,3}) (.*)$/.exec(line);
    if (h) out.push(`<h${h[1].length}>${inline(h[2])}</h${h[1].length}>`);
    else if (line.startsWith('- ')) {
      out.push('<ul>');
      for (; i < lines.length && lines[i].startsWith('- '); i++) out.push(`<li>${inline(lines[i].slice(2))}</li>`);
      i--;
      out.push('</ul>');
    } else if (line.startsWith('|')) {
      const rows = [];
      for (; i < lines.length && lines[i].startsWith('|'); i++) rows.push(lines[i]);
      i--;
      const cells = (/** @type {string} */ r) =>
        r
          .slice(1, r.endsWith('|') ? -1 : undefined)
          .split('|')
          .map((c) => c.trim());
      const [head, sep, ...body] = rows;
      const right = sep ? cells(sep).map((c) => c.endsWith(':')) : [];
      const td = (/** @type {string} */ tag, /** @type {string} */ c, /** @type {number} */ j) =>
        `<${tag}${right[j] ? ' class="num"' : ''}>${inline(c)}</${tag}>`;
      out.push(
        '<div class="table"><table>',
        `<thead><tr>${cells(head)
          .map((c, j) => td('th', c, j))
          .join('')}</tr></thead>`,
        `<tbody>${body
          .map(
            (r) =>
              `<tr>${cells(r)
                .map((c, j) => td('td', c, j))
                .join('')}</tr>`,
          )
          .join('')}</tbody>`,
        '</table></div>',
      );
    } else if (line.startsWith('    ') || line.startsWith('```')) {
      // Pre-formatted blocks (the status table) keep their alignment.
      const fenced = line.startsWith('```');
      const block = [];
      for (i += fenced ? 1 : 0; i < lines.length && (fenced ? !lines[i].startsWith('```') : lines[i].startsWith('    ')); i++)
        block.push(fenced ? lines[i] : lines[i].slice(4));
      if (!fenced) i--;
      out.push(`<pre>${esc(block.join('\n'))}</pre>`);
    } else if (line.trim()) out.push(`<p>${inline(line)}</p>`);
  }
  return out.join('\n');
}

